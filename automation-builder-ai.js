/**
 * Automation Builder AI assistant (loaded after admin-automation-builder.js).
 *  - "AI Build": describe a workflow in plain English, review the generated steps, apply to canvas
 *  - "Suggest Next Step": AI proposes one step, inserted before the End step after confirmation
 * Server side: routes/automation.js -> services/automation-ai-service.js (ChatGPT or rule-based fallback).
 */
(function () {
    const AI_API = `${API_BASE}/api/automations/ai`;

    function ensureModal() {
        let modal = document.getElementById('aiBuildModal');
        if (modal) return modal;
        modal = document.createElement('div');
        modal.id = 'aiBuildModal';
        modal.style.cssText = 'display:none;position:fixed;inset:0;z-index:10000;background:rgba(15,23,42,0.45);align-items:center;justify-content:center;padding:16px;';
        modal.innerHTML = `
            <div style="background:#fff;border-radius:16px;width:100%;max-width:640px;max-height:90vh;overflow:auto;box-shadow:0 20px 50px rgba(15,23,42,0.25);font-family:inherit;">
                <div style="display:flex;align-items:center;justify-content:space-between;padding:18px 22px;border-bottom:1px solid #e2e8f0;">
                    <div style="display:flex;align-items:center;gap:10px;">
                        <i data-lucide="sparkles" style="color:#7c3aed;width:20px;height:20px;"></i>
                        <div>
                            <div style="font-weight:800;font-size:1.05rem;color:#0f172a;">AI Workflow Builder</div>
                            <div id="aiBuildSource" style="font-size:0.75rem;color:#64748b;">Describe the automation in plain English</div>
                        </div>
                    </div>
                    <button type="button" onclick="closeAiBuildModal()" style="background:none;border:none;cursor:pointer;color:#64748b;font-size:1.3rem;line-height:1;" aria-label="Close">&times;</button>
                </div>
                <div style="padding:18px 22px;">
                    <textarea id="aiBuildPrompt" rows="4" maxlength="2000" placeholder="e.g. When an employee resigns, ask the direct manager to approve within 48 hours, escalate to Head of HR if not approved, wait 2 days, start full and final settlement and notify HR and the employee."
                        style="width:100%;box-sizing:border-box;border:1px solid #cbd5e1;border-radius:10px;padding:12px;font-family:inherit;font-size:0.9rem;resize:vertical;"></textarea>
                    <div id="aiBuildStatus" style="font-size:0.82rem;color:#64748b;margin-top:8px;min-height:1.2em;"></div>
                    <div id="aiBuildPreview" style="margin-top:10px;"></div>
                </div>
                <div style="display:flex;justify-content:flex-end;gap:10px;padding:14px 22px;border-top:1px solid #e2e8f0;">
                    <button type="button" class="btn-builder" onclick="closeAiBuildModal()">Cancel</button>
                    <button type="button" class="btn-builder btn-builder-simulate" id="aiBuildGenerateBtn" onclick="generateAiWorkflow()">
                        <i data-lucide="sparkles" size="16"></i><span>Generate</span>
                    </button>
                    <button type="button" class="btn-builder btn-builder-primary" id="aiBuildApplyBtn" style="display:none;" onclick="applyAiWorkflow()">
                        <i data-lucide="check" size="16"></i><span>Use This Workflow</span>
                    </button>
                </div>
            </div>`;
        document.body.appendChild(modal);
        return modal;
    }

    let generated = null;

    window.openAiBuildModal = function () {
        const modal = ensureModal();
        generated = null;
        document.getElementById('aiBuildStatus').textContent = '';
        document.getElementById('aiBuildPreview').innerHTML = '';
        document.getElementById('aiBuildApplyBtn').style.display = 'none';
        modal.style.display = 'flex';
        if (window.lucide) lucide.createIcons();
        document.getElementById('aiBuildPrompt').focus();
    };

    window.closeAiBuildModal = function () {
        const modal = document.getElementById('aiBuildModal');
        if (modal) modal.style.display = 'none';
    };

    async function postJson(path, body) {
        const res = await fetch(`${AI_API}/${path}`, {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify(body)
        });
        const json = await res.json().catch(() => ({}));
        if (!res.ok || !json.success) throw new Error(json.error || `Request failed (HTTP ${res.status})`);
        return json;
    }

    function sourceLabel(source) {
        return source === 'openai' ? 'Generated by ChatGPT' : 'Generated by the built-in rule-based assistant (add OPENAI_API_KEY for ChatGPT)';
    }

    window.generateAiWorkflow = async function () {
        const prompt = document.getElementById('aiBuildPrompt').value.trim();
        const status = document.getElementById('aiBuildStatus');
        const btn = document.getElementById('aiBuildGenerateBtn');
        if (!prompt) {
            status.textContent = 'Describe the workflow first.';
            return;
        }
        btn.disabled = true;
        status.textContent = 'Generating workflow...';
        document.getElementById('aiBuildPreview').innerHTML = '';
        try {
            generated = await postJson('generate', { prompt });
            status.textContent = sourceLabel(generated.source);
            document.getElementById('aiBuildPreview').innerHTML = `
                <div style="font-weight:800;color:#0f172a;margin-bottom:4px;">${escapeHtml(generated.name)}</div>
                ${generated.explanation ? `<div style="font-size:0.82rem;color:#475569;margin-bottom:10px;">${escapeHtml(generated.explanation)}</div>` : ''}
                <ol style="margin:0;padding-left:20px;font-size:0.85rem;color:#334155;line-height:1.7;">
                    ${generated.steps.map(s => `<li><strong>${escapeHtml((ELEMENT_SPECS[s.type] || {}).label || s.type)}:</strong> ${escapeHtml(s.title)}</li>`).join('')}
                </ol>`;
            document.getElementById('aiBuildApplyBtn').style.display = 'inline-flex';
        } catch (err) {
            status.textContent = 'Could not generate: ' + err.message;
        } finally {
            btn.disabled = false;
            if (window.lucide) lucide.createIcons();
        }
    };

    window.applyAiWorkflow = async function () {
        if (!generated) return;
        if (currentWorkflow.steps.length) {
            const ok = await showConfirmModal({
                title: 'Replace Current Workflow?',
                message: `The canvas will be replaced with <strong>${escapeHtml(generated.name)}</strong> (${generated.steps.length} steps). Nothing is saved until you click Deploy Workflow.`,
                confirmText: 'Replace',
                danger: false,
                icon: 'sparkles'
            });
            if (!ok) return;
        }
        currentWorkflow = {
            id: 'wf_' + Date.now(),
            name: generated.name,
            description: generated.description,
            module: generated.module,
            status: 'DRAFT',
            isAiGenerated: true,
            steps: generated.steps
        };
        closeAiBuildModal();
        renderCanvas();
        selectNode(0);
        showToast('AI workflow added to the canvas. Review the steps, then click Deploy Workflow.', 'success');
    };

    window.suggestAiNextStep = async function () {
        showToast('Asking AI for the next step...', 'info');
        try {
            const res = await postJson('suggest-next', { workflow: currentWorkflow });
            const spec = ELEMENT_SPECS[res.step.type] || {};
            const title = res.step.title && res.step.title !== res.step.type ? res.step.title : (spec.defaultTitle || res.step.type);
            const ok = await showConfirmModal({
                title: 'AI Suggested Step',
                message: `<strong>${escapeHtml(spec.label || res.step.type)}: ${escapeHtml(title)}</strong><br><br>${escapeHtml(res.reason || '')}<br><br><span style="font-size:0.8rem;color:#64748b;">${escapeHtml(sourceLabel(res.source))}</span>`,
                confirmText: 'Add Step',
                danger: false,
                icon: 'sparkles'
            });
            if (!ok) return;
            const step = {
                ...res.step,
                title,
                description: res.step.description || spec.defaultDesc || '',
                config: Object.keys(res.step.config || {}).length ? res.step.config : JSON.parse(JSON.stringify(spec.defaultConfig || {}))
            };
            // Insert before the End step (or at the end if there is none)
            const endIndex = currentWorkflow.steps.findIndex(s => s.type === 'end');
            const index = endIndex === -1 ? currentWorkflow.steps.length : endIndex;
            currentWorkflow.steps.splice(index, 0, step);
            renderCanvas();
            selectNode(index);
            showToast('Step added. Click Deploy Workflow to save.', 'success');
        } catch (err) {
            showToast('AI suggestion failed: ' + escapeHtml(err.message), 'warning');
        }
    };
})();
