// DELETE /api/workflow-builder/:id — Delete workflow
router.delete('/:id', (req, res) => {
    try {
        const deleted = workflowBuilderService.deleteWorkflow(req.params.id, { actor: req.body?.actor || 'HR Administrator' });
        if (!deleted) {
            return res.status(404).json({ success: false, error: `Workflow '${req.params.id}' not found.` });
        }
        res.status(200).json({ success: true, deleted: true, message: 'Workflow deleted successfully.' });
    } catch (err) {
        logger.error(`[WorkflowBuilderAPI] Error deleting workflow '${req.params.id}':`, err);
        res.status(404).json({ success: false, error: err.message });
    }
});

// POST /api/workflow-builder/:id/activate & /versions/publish — Promote tested draft to Active
