// POST /api/workflow-builder — Save (create) a new workflow
router.post('/', async (req, res) => {
    try {
        const workflowData = req.body || {};
        const actor = req.body?.actor || 'HR Administrator';
        if (!workflowData.name) {
            return res.status(400).json({ success: false, error: 'Workflow name is required.' });
        }

        const workflow = workflowBuilderService.saveWorkflow(workflowData, null, { actor });
        res.status(201).json({
            success: true,
            workflow,
            data: workflow,
            message: `Workflow '${workflow.name}' saved successfully.`
        });
    } catch (err) {
        const isValidation = err.message.includes('Validation failed');
        logger.error('[WorkflowBuilderAPI] Error saving workflow:', err);
        res.status(isValidation ? 422 : 500).json({ success: false, error: err.message });
    }
});

// GET /api/workflow-builder/:id — Get full workflow
router.get('/:id', (req, res) => {
    try {
        const workflow = workflowBuilderService.getWorkflow(req.params.id);
        if (!workflow) {
            return res.status(404).json({ success: false, error: `Workflow '${req.params.id}' not found.` });
        }
        res.status(200).json({ success: true, workflow, data: workflow });
    } catch (err) {
        logger.error(`[WorkflowBuilderAPI] Error fetching workflow '${req.params.id}':`, err);
        res.status(404).json({ success: false, error: err.message });
    }
});

// PUT /api/workflow-builder/:id — Update existing workflow
