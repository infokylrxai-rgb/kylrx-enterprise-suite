// POST /api/workflow-builder/ai-generate — AI Automation Creator (Natural Language to Draft Workflow)
router.post('/ai-generate', (req, res) => {
    try {
        const { prompt, options } = req.body || {};
        if (!prompt) {
            return res.status(400).json({ success: false, error: 'A natural-language prompt is required.' });
        }

        const result = workflowBuilderService.createWorkflowFromPrompt(prompt, options);
        res.status(200).json({
            success: true,
            workflow: result.workflow,
            data: result.workflow,
            nodeChain: result.nodeChain,
            explanation: result.explanation,
            confidence: result.confidence,
            summary: result.summary,
            message: 'Draft workflow generated by Kylrx AI (Review mode active).'
        });
    } catch (err) {
        logger.error('[WorkflowBuilderAPI] Error generating AI workflow:', err);
        res.status(400).json({ success: false, error: err.message });
    }
});

